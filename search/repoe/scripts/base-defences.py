#!/usr/bin/env python3
"""repoe, added extract: the per-base defence ranges the export carries, for the base-defence percentile.

Deleted at c756bd38 with the scripts nothing opened, and restored (issue #53) because
tools/defence-table.py checks the shipped defence table against this extract row for row at every run:
after the pin moves (phase 3b), a moved range is a regeneration of this extract and then of the table,
in the order tools/game-diff.py prints.

    python3 -I search/repoe/scripts/base-defences.py           # writes data/base-defences.csv
    python3 -I search/repoe/scripts/base-defences.py --check   # exits 1 when the file on disk differs from what the clone gives

Inputs (read-only; every one is required before any is read, tools/sources.py — an absent input or the
clone at another commit is a refusal, and nothing is written):
  $ACQ_CLONES/poe1/data/base_items.json (default: beside this repository)
                                             every base: name, class, release state, domain and
                                             `properties.armour` / `.evasion` / `.energy_shield` / `.ward`
                                             as `{min, max}` or null, and `.block` as a number or null

Outputs (data/, regenerable; the first line names this script, its input and the pin it was read at):
  base-defences.csv   one row per export base entry carrying at least one non-null defence or block value,
                      keyed by its metadata id: the four ranges as min/max pairs and block, empty where
                      null. A base with every one null is left out. Rows are export entries, not names: a
                      name with several metadata entries (Two-Toned Boots) keeps one row per entry, its
                      own ranges on each, told apart by `metadata_id`.

Printed: bases with any non-null defence (the CSV's row count), and a per-class count of them.
"""

import collections
import csv
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TRACK = os.path.dirname(HERE)
SEARCH = os.path.dirname(TRACK)
ROOT = os.path.dirname(SEARCH)
sys.path.insert(0, os.path.join(ROOT, "tools"))
from sources import PINS, POE1, require  # noqa: E402  the clone, at the manifest's commit
BASE_ITEMS = os.path.join(POE1, "data", "base_items.json")
OUT = os.path.join(TRACK, "data", "base-defences.csv")
HEADER = f"# generated by scripts/base-defences.py from poe1/data/base_items.json @ {PINS['poe1'][:8]}"

RANGES = ("armour", "evasion", "energy_shield", "ward")  # each `{min, max}` or null


def defences(b):
    """(the four `{min, max}` or None, block or None) for one base entry."""
    p = b.get("properties") or {}
    return [p.get(k) for k in RANGES], p.get("block")


def main():
    check = "--check" in sys.argv[1:]
    require(POE1)
    bases = json.load(open(BASE_ITEMS))

    rows = []
    per_class = collections.Counter()
    for key, b in sorted(bases.items(), key=lambda kv: (kv[1]["name"], kv[0])):
        ranges, block = defences(b)
        if not any(r is not None for r in ranges) and block is None:
            continue
        cells = []
        for r in ranges:
            cells += ["", ""] if r is None else [r["min"], r["max"]]
        rows.append([key, b["name"], b["item_class"], b["release_state"], b["domain"]] + cells +
                    ["" if block is None else block])
        per_class[b["item_class"]] += 1

    f = io.StringIO()
    f.write(HEADER + "\n")
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["metadata_id", "name", "item_class", "release_state", "domain",
                "armour_min", "armour_max", "evasion_min", "evasion_max",
                "energy_shield_min", "energy_shield_max", "ward_min", "ward_max", "block"])
    w.writerows(rows)
    text = f.getvalue()

    summary = (f"export base entries: {len(bases)}; with a non-null defence or block: {len(rows)} "
               f"({len({r[1] for r in rows})} distinct names)")
    if check:
        if not os.path.exists(OUT) or open(OUT, newline="").read() != text:
            sys.exit(f"{OUT} differs from what the clone at {PINS['poe1'][:8]} gives: regenerate and review the diff")
        print(f"ok      {os.path.relpath(OUT, ROOT)} is what the clone gives: {summary}")
        return
    with open(OUT, "w", newline="") as out:
        out.write(text)
    print(summary)
    print("  per class:", ", ".join(f"{c} {n}" for c, n in per_class.most_common()))
    counts = [f"{k} {sum(1 for r in rows if r[5 + 2 * i] != '')}" for i, k in enumerate(RANGES)]
    counts.append(f"block {sum(1 for r in rows if r[13] != '')}")
    print("  with a non-null:", ", ".join(counts))


if __name__ == "__main__":
    main()
