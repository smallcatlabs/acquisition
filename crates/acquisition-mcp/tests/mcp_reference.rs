//! `MCP-REFERENCE.md` is generated from the server's own `initialize`
//! instructions and `tools/list` — every tool, its description and its
//! arguments as the schema declares them — and this test keeps the
//! committed copy equal to it. A golden file, not a frozen one (P5):
//! drift fails here, and
//! `ACQ_UPDATE_FIXTURES=1 cargo test -p acquisition-mcp --test main mcp_reference`
//! rewrites it. An agent reads the file without building; the writer
//! builds anyway. The CLI's counterpart is `CLI-REFERENCE.md`.

use crate::harness;

use harness::Mcp;
use serde_json::Value;

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../MCP-REFERENCE.md");

/// Doc comments arrive with their source line breaks; one line per field.
fn flat(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn render(instructions: &str, tools: &[Value]) -> String {
    let mut out = String::from(
        "# `acq-mcp` — tool reference\n\n\
         Generated by `crates/acquisition-mcp/tests/mcp_reference.rs` from the \
         server's own `initialize` instructions and `tools/list`; a golden file \
         the test keeps equal to the binary. Do not edit: change the tool's \
         attributes in `crates/acquisition-mcp/src/main.rs` and regenerate with \
         `ACQ_UPDATE_FIXTURES=1 cargo test -p acquisition-mcp --test main mcp_reference`. \
         The CLI's verbs are `CLI-REFERENCE.md`.\n\n\
         ## Instructions (sent at `initialize`)\n\n",
    );
    out.push_str(&flat(instructions));
    out.push_str("\n\n## Tools\n\n");
    for tool in tools {
        let name = tool["name"].as_str().unwrap_or("?");
        let desc = flat(tool["description"].as_str().unwrap_or(""));
        out.push_str(&format!("### `{name}`\n\n{desc}\n\n"));
        let schema = &tool["inputSchema"];
        let required: Vec<&str> = schema["required"]
            .as_array()
            .map(|a| a.iter().filter_map(Value::as_str).collect())
            .unwrap_or_default();
        match schema["properties"].as_object() {
            Some(props) if !props.is_empty() => {
                let mut names: Vec<&String> = props.keys().collect();
                names.sort();
                for arg in names {
                    let p = &props[arg];
                    let ty = match &p["type"] {
                        Value::String(t) => t.clone(),
                        Value::Array(ts) => ts
                            .iter()
                            .filter_map(Value::as_str)
                            .collect::<Vec<_>>()
                            .join(" | "),
                        _ => "object".to_string(),
                    };
                    let req = if required.contains(&arg.as_str()) {
                        ", required"
                    } else {
                        ""
                    };
                    let d = flat(p["description"].as_str().unwrap_or(""));
                    let sep = if d.is_empty() { "" } else { " — " };
                    out.push_str(&format!("- `{arg}` ({ty}{req}){sep}{d}\n"));
                }
                out.push('\n');
            }
            _ => out.push_str("No arguments.\n\n"),
        }
    }
    out
}

#[test]
fn the_reference_matches_the_server() {
    let scratch = harness::scratch("mref");
    let base = scratch.0.clone();
    let mut mcp = Mcp::start(&base, &[]);
    let tools = mcp.list_tools();
    let actual = render(&mcp.instructions, &tools);
    let _ = mcp.child.kill();
    assert!(tools.len() >= 10, "tools/list returned {}", tools.len());
    if std::env::var_os("ACQ_UPDATE_FIXTURES").is_some() {
        std::fs::write(PATH, &actual).unwrap();
    }
    let expected = std::fs::read_to_string(PATH).unwrap_or_else(|e| panic!("{PATH}: {e}"));
    harness::same_text(
        &expected,
        &actual,
        "MCP-REFERENCE.md",
        "ACQ_UPDATE_FIXTURES=1 cargo test -p acquisition-mcp --test main mcp_reference",
    );
}

/// The answer-facts seat (run 1, MCP fault 8; call 1): the README said
/// the server's 25 tools where it had 26, `leagues` missing from the
/// list. The README's tool count is the server's, and its list names
/// each tool once: read from the README's sentence ("its N tools do what
/// the CLI does: …", to the paragraph's end) and compared to `tools/list`.
#[test]
fn mcp8_the_readmes_tool_count_and_list_are_the_servers() {
    let readme =
        std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../README.md")).unwrap();
    let paragraph = readme
        .split("\n\n")
        .map(flat)
        .find(|p| p.contains(" tools do what the CLI does"))
        .expect("the README's sentence on the server's tools");
    let at = paragraph.find(" tools do what the CLI does").unwrap();
    let count: usize = paragraph[..at]
        .rsplit(' ')
        .next()
        .and_then(|n| n.parse().ok())
        .expect("a number before ` tools do what the CLI does`");
    let paragraph = &paragraph[at..];
    let mut named: Vec<&str> = paragraph.split('`').skip(1).step_by(2).collect();
    named.sort_unstable();
    let scratch = harness::scratch("mref-readme");
    let mut mcp = Mcp::start(&scratch.0, &[]);
    let tools = mcp.list_tools();
    let _ = mcp.child.kill();
    let mut served: Vec<&str> = tools.iter().filter_map(|t| t["name"].as_str()).collect();
    served.sort_unstable();
    assert_eq!(count, served.len(), "the README's count");
    assert_eq!(named, served, "the README's list");
}

/// The h2 review's fifth finding: "Intent only" stood in `price_set` and
/// `price_clear` after the server's instructions had dropped the word. The
/// word names a mechanism a reader cannot parse (C146, a count says what
/// it counts); it stands in what the server sends only as a JSON name,
/// in backticks, found case-insensitively. What is read on demand is
/// sent too (#83): `describe` whole under `all`, every section the tools
/// point to.
#[test]
fn the_old_word_intent_stands_only_as_a_json_name() {
    let scratch = harness::scratch("mref-intent");
    let base = scratch.0.clone();
    let mut mcp = Mcp::start(&base, &[]);
    let tools = mcp.list_tools();
    let described = mcp.result("describe", serde_json::json!({ "names": ["all"] }));
    let mut text = render(&mcp.instructions, &tools);
    text.push_str(described["content"][0]["text"].as_str().unwrap_or_default());
    let _ = mcp.child.kill();
    let lower = text.to_lowercase();
    let stray: Vec<&str> = lower
        .match_indices("intent")
        .filter(|(at, _)| {
            !(lower[..*at].ends_with('`') && lower[at + "intent".len()..].starts_with('`'))
        })
        .map(|(at, _)| {
            lower
                .get(at.saturating_sub(40)..(at + 46).min(lower.len()))
                .unwrap_or("intent")
        })
        .collect();
    assert!(
        stray.is_empty(),
        "the old word, outside a JSON name: {stray:#?}"
    );
}
